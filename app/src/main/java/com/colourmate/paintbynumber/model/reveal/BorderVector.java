package com.colourmate.paintbynumber.model.reveal;

import android.graphics.Path;
import android.util.Log;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * The drawn line as a vector, so it stays sharp however far the player zooms.
 *
 * <p><b>Why this exists:</b> {@code border.png} is a 1254px raster. Fitted to the screen that is
 * plenty, but the game is played zoomed in, and at 5x one source pixel covers about four screen
 * pixels — the outlines visibly break into squares. Bitmap filtering cannot fix that; there is no
 * more detail in the file to show.
 *
 * <p>The backend now also publishes {@code border.svg}: the same ink traced as filled shapes
 * (reveal_game_builder.ink_svg), which reproduces the varying stroke weight exactly and has no
 * resolution at all.
 *
 * <p><b>No SVG library is needed.</b> That file is generated by our own exporter and contains a
 * single path, so it only ever uses <b>M</b>, <b>L</b>, <b>Q</b> and <b>Z</b> — and their relative
 * forms, which is what the exporter now writes because the deltas are one or two digits where the
 * absolute coordinates ran to four (the mandala's file went 513 KB to 259 KB). Parsing that is a
 * few lines, and it keeps the APK the size it is. Anything more exotic in the data is treated as
 * unparseable and the caller falls back to the PNG — which since §8.5bo is drawn from these very
 * curves, so the fallback is the identical drawing rather than a worse one.
 */
public final class BorderVector {

    private static final String TAG = "BorderVector";

    /** viewBox width/height, so the caller can scale the path onto the level's pixel grid. */
    public final float width, height;
    public final Path path;

    private BorderVector(float width, float height, Path path) {
        this.width = width;
        this.height = height;
        this.path = path;
    }

    private static final Pattern VIEWBOX =
            Pattern.compile("viewBox=\"\\s*([-\\d.]+)\\s+([-\\d.]+)\\s+([\\d.]+)\\s+([\\d.]+)");
    private static final Pattern PATH_D = Pattern.compile("<path[^>]*\\bd=\"([^\"]*)\"");

    /** Returns null when the file is missing or is not the simple shape we emit. */
    public static BorderVector parse(InputStream in) {
        if (in == null) return null;
        try {
            StringBuilder sb = new StringBuilder();
            try (BufferedReader r = new BufferedReader(
                    new InputStreamReader(in, StandardCharsets.UTF_8), 1 << 16)) {
                char[] buf = new char[1 << 16];
                int n;
                while ((n = r.read(buf)) > 0) sb.append(buf, 0, n);
            }
            String svg = sb.toString();

            float w = 0f, h = 0f;
            Matcher vb = VIEWBOX.matcher(svg);
            if (vb.find()) {
                w = Float.parseFloat(vb.group(3));
                h = Float.parseFloat(vb.group(4));
            }
            if (w <= 0f || h <= 0f) return null;

            // Only the FILLED ink export is usable. Items published before ink_svg() existed carry
            // a completely different file under the same name — hundreds of per-region outlines
            // with fill="none" and stroke="#000". Filling those paints the picture inside out.
            // Recognise the real thing by its signature and fall back to the raster otherwise.
            if (!svg.contains("fill-rule=\"evenodd\"") || !svg.contains("fill=\"#000\"")) {
                Log.d(TAG, "border.svg is not the filled ink export — using the raster");
                return null;
            }

            Path path = new Path();
            // evenodd: a hole inside a stroke must stay a hole, exactly as the exporter intended.
            path.setFillType(Path.FillType.EVEN_ODD);
            boolean any = false;
            Matcher pm = PATH_D.matcher(svg);
            while (pm.find()) {
                if (!appendPath(path, pm.group(1))) return null;
                any = true;
            }
            return any ? new BorderVector(w, h, path) : null;
        } catch (Throwable t) {
            Log.w(TAG, "border.svg unreadable — falling back to the raster", t);
            return null;
        }
    }

    /** Appends one subpath run. Returns false on anything else, so we can fall back. */
    private static boolean appendPath(Path path, String d) {
        int i = 0, n = d.length();
        float[] pt = new float[2], pt2 = new float[2];
        float penX = 0f, penY = 0f, startX = 0f, startY = 0f;
        while (i < n) {
            char c = d.charAt(i);
            if (c == ' ' || c == ',' || c == '\n' || c == '\r' || c == '\t') { i++; continue; }
            if (c == 'Z' || c == 'z') {
                path.close();
                penX = startX; penY = startY;       // close returns the pen to the subpath start
                i++;
                continue;
            }
            char u = Character.toUpperCase(c);
            if (u != 'M' && u != 'L' && u != 'Q') return false;   // cubics, arcs — not ours
            boolean rel = c != u;                                 // lower case = relative
            i++;
            int read = readPair(d, i, pt);
            if (read < 0) return false;
            i = read;
            float ax = rel ? penX + pt[0] : pt[0];
            float ay = rel ? penY + pt[1] : pt[1];
            if (u == 'Q') {
                // Q is what makes the line look drawn rather than traced: the exporter runs a
                // quadratic through the polygon's midpoints with each vertex as its control
                // point, so corners become curves and a traced circle is a circle again.
                // Both deltas of a relative q are measured from the pen BEFORE the command.
                read = readPair(d, i, pt2);
                if (read < 0) return false;
                i = read;
                float ex = rel ? penX + pt2[0] : pt2[0];
                float ey = rel ? penY + pt2[1] : pt2[1];
                path.quadTo(ax, ay, ex, ey);
                penX = ex; penY = ey;
            } else if (u == 'M') {
                path.moveTo(ax, ay);
                penX = startX = ax; penY = startY = ay;
            } else {
                path.lineTo(ax, ay);
                penX = ax; penY = ay;
            }
        }
        return true;
    }

    /** Reads "x y" (space or comma separated) starting at i; returns the new index, or -1. */
    private static int readPair(String d, int i, float[] out) {
        int n = d.length();
        for (int k = 0; k < 2; k++) {
            while (i < n && (d.charAt(i) == ' ' || d.charAt(i) == ',')) i++;
            int start = i;
            while (i < n) {
                char ch = d.charAt(i);
                if ((ch >= '0' && ch <= '9') || ch == '-' || ch == '+' || ch == '.'
                        || ch == 'e' || ch == 'E') i++;
                else break;
            }
            if (i == start) return -1;
            try {
                out[k] = Float.parseFloat(d.substring(start, i));
            } catch (NumberFormatException e) {
                return -1;
            }
        }
        return i;
    }
}
